// APIから取得した画数のキャッシュ
const API_CACHE = {};

function getStrokeCount(char) {
  if (STROKE_MAP[char] !== undefined) return STROKE_MAP[char];
  if (API_CACHE[char] !== undefined) return API_CACHE[char];
  return null;
}

function getTotalStrokes(text) {
  let total = 0;
  let unknown = [];
  for (const char of text) {
    const s = getStrokeCount(char);
    if (s === null) {
      // CJK漢字かどうかチェック
      const code = char.charCodeAt(0);
      const isKanji = (code >= 0x4E00 && code <= 0x9FFF)
                   || (code >= 0x3400 && code <= 0x4DBF)
                   || (code >= 0xF900 && code <= 0xFAFF);
      if (isKanji) unknown.push(char);
      // 漢字以外（ひらがな・カタカナ・記号）は無視
    } else {
      total += s;
    }
  }
  return { total, unknown };
}

// 未知の漢字をKanjiAPIで一括取得
async function fetchUnknownStrokes(chars) {
  // 重複除去
  const unique = [...new Set(chars)].filter(c => API_CACHE[c] === undefined);
  if (unique.length === 0) return;

  await Promise.all(unique.map(async (char) => {
    try {
      const res = await fetch(`https://kanjiapi.dev/v1/kanji/${encodeURIComponent(char)}`);
      if (res.ok) {
        const data = await res.json();
        if (data.stroke_count) {
          API_CACHE[char] = data.stroke_count;
          STROKE_MAP[char] = data.stroke_count; // 以降はローカルで解決
        }
      }
    } catch (e) {
      // ネットワークエラー時は0として扱う
      API_CACHE[char] = 0;
    }
  }));
}
